export interface IconPickerProps {
  value?: string;
  onValueChange?: (icon: string) => void;
  placeholder?: string;
  className?: string;
  iconSet?: "lucide" | "emoji";
}

export function IconPicker({
  value,
  onValueChange,
  placeholder = "Select an icon...",
  className,
  iconSet = "lucide",
}: IconPickerProps) {
  const [open, setOpen] = React.useState(false);
  const [searchQuery, setSearchQuery] = React.useState("");

  const icons = iconSets[iconSet];
  const filteredIcons = icons.filter(icon => icon.toLowerCase().includes(searchQuery.toLowerCase()));

  const selectedIcon = value ? icons.find(icon => icon === value) : null;

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          role="combobox"
          aria-expanded={open}
          className={cn("w-full justify-between", className)}
        >
          {selectedIcon ? (
            <div className="flex items-center gap-2">
              {iconSet === "lucide" ? (
                <span className="font-mono text-sm">{selectedIcon}</span>
              ) : (
                <span className="text-lg">{selectedIcon}</span>
              )}
            </div>
          ) : (
            placeholder
          )}
          <Search className="ml-2 h-4 w-4 shrink-0 opacity-50" />
        </Button>
      </PopoverTrigger>
      <PopoverContent className="w-80 p-0">
        <Command>
          <CommandInput placeholder={`Search ${iconSet} icons...`} value={searchQuery} onValueChange={setSearchQuery} />
          <CommandList>
            <CommandEmpty>No icons found.</CommandEmpty>
            <CommandGroup>
              <div className="grid grid-cols-8 gap-1 p-2">
                {filteredIcons.map(icon => (
                  <CommandItem
                    key={icon}
                    value={icon}
                    onSelect={() => {
                      onValueChange?.(icon);
                      setOpen(false);
                    }}
                    className="h-auto justify-center p-2"
                  >
                    <div className="flex flex-col items-center gap-1">
                      {iconSet === "lucide" ? (
                        <span className="font-mono text-sm">{icon}</span>
                      ) : (
                        <span className="text-lg">{icon}</span>
                      )}
                      {value === icon && <Check className="h-3 w-3" />}
                    </div>
                  </CommandItem>
                ))}
              </div>
            </CommandGroup>
          </CommandList>
        </Command>
      </PopoverContent>
    </Popover>
  );
}
